// 產生 vendor/three-lite.js：只打包網站實際用到的 Three.js 功能。
// 掃描所有前端 JS 的 `THREE.Xxx` 與 three/addons 匯入，交給 esbuild tree-shake。
//
// 每次產生後會：
//   1. 依檔案內容算出版本碼，寫進 index.html 的 importmap（three-lite.js?v=xxxx），
//      確保瀏覽器不會拿快取裡的舊版配新版程式碼（曾因此導致 3D 場景無法啟動）
//   2. 重新計算 importmap 的 CSP hash，寫進 _headers
//
// 用法：
//   npm run build:three          修改 3D 程式碼、用到新的 Three.js 類別後執行
//   npm run check:three          部署前檢查：版本是否最新（CI 使用，不寫檔）
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, statSync, mkdtempSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { tmpdir } from 'node:os';

const CHECK = process.argv.includes('--check');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sources = ['world.js', 'people.js', 'vignettes.js'].filter((f) => {
  try { statSync(join(root, f)); return true; } catch { return false; }
});

const core = new Set();
const addons = new Map(); // addon path -> Set(names)
for (const f of sources) {
  const code = readFileSync(join(root, f), 'utf8');
  for (const [, name] of code.matchAll(/THREE\.([A-Z][A-Za-z0-9_]*)/g)) core.add(name);
  for (const [, names, path] of code.matchAll(/import\s*\{([^}]+)\}\s*from\s*'three\/addons\/([^']+)'/g)) {
    if (!addons.has(path)) addons.set(path, new Set());
    names.split(',').map((s) => s.trim()).filter(Boolean).forEach((n) => addons.get(path).add(n));
  }
}

const lines = [`export { ${[...core].sort().join(', ')} } from 'three';`];
for (const [path, names] of [...addons].sort()) lines.push(`export { ${[...names].sort().join(', ')} } from 'three/examples/jsm/${path}';`);
mkdirSync(join(root, 'node_modules/.cache'), { recursive: true });
const entry = join(root, 'node_modules/.cache/three-entry.js');
writeFileSync(entry, lines.join('\n') + '\n');

const outfile = CHECK ? join(mkdtempSync(join(tmpdir(), 'three-lite-')), 'three-lite.js') : join(root, 'vendor/three-lite.js');
await build({
  entryPoints: [entry],
  bundle: true,
  format: 'esm',
  minify: true,
  target: 'es2020',
  legalComments: 'none',
  banner: { js: '/* Three.js (MIT) — https://threejs.org — tree-shaken build for this site, generated by scripts/build-three.mjs */' },
  outfile,
  absWorkingDir: root,
});

const bundle = readFileSync(outfile);
const version = createHash('sha256').update(bundle).digest('hex').slice(0, 10);
const IMPORTMAP_URL = /\.\/vendor\/three-lite\.js(\?v=[0-9a-f]+)?/g;
const htmlPath = join(root, 'index.html');
const html = readFileSync(htmlPath, 'utf8');
const nextHtml = html.replace(IMPORTMAP_URL, `./vendor/three-lite.js?v=${version}`);
const importmap = nextHtml.match(/<script type="importmap">([\s\S]*?)<\/script>/)?.[1];
if (!importmap) throw new Error('index.html 找不到 importmap');
const cspHash = `'sha256-${createHash('sha256').update(importmap).digest('base64')}'`;
const headersPath = join(root, '_headers');
const headers = readFileSync(headersPath, 'utf8');
const nextHeaders = headers.replace(/'sha256-[A-Za-z0-9+/=]+'/, cspHash);

if (CHECK) {
  const problems = [];
  if (!bundle.equals(readFileSync(join(root, 'vendor/three-lite.js')))) problems.push('vendor/three-lite.js 不是最新的打包結果');
  if (nextHtml !== html) problems.push('index.html importmap 的版本碼不是最新');
  if (nextHeaders !== headers) problems.push('_headers 的 CSP hash 與 importmap 不符');
  if (problems.length) {
    console.error(`✗ ${problems.join('；')}。請執行 npm run build:three 後再提交。`);
    process.exit(1);
  }
  console.log(`✓ three-lite.js v=${version} 與程式碼一致（${core.size} 個核心類別，${addons.size} 個 addon）`);
} else {
  writeFileSync(htmlPath, nextHtml);
  writeFileSync(headersPath, nextHeaders);
  const kb = (bundle.length / 1024).toFixed(0);
  console.log(`vendor/three-lite.js: ${kb} KB, v=${version}, ${core.size} core exports, ${addons.size} addon modules (${sources.join(', ')})`);
}
